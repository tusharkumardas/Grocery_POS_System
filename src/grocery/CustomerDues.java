     private void viewHistory(int customerId) {
    DefaultTableModel model = (DefaultTableModel) historyTable.getModel();
    model.setRowCount(0); // Clear table

    String sql = "SELECT created_at, invoice_no, net_amount, amount_paid, amount_due " +
                 "FROM sales WHERE customer_id = ? ORDER BY created_at DESC";

    try (Connection con = ConnectionProvider.getCon();
         PreparedStatement ps = con.prepareStatement(sql)) {
        
        ps.setInt(1, customerId);
        ResultSet rs = ps.executeQuery();

        double totalDue = 0;

        while (rs.next()) {
            Object[] row = {
                rs.getTimestamp("created_at"),   // Date
                rs.getString("invoice_no"),      // Invoice No
                rs.getDouble("net_amount"),      // Net Amount
                rs.getDouble("amount_paid"),     // Paid
                rs.getDouble("amount_due")       // Due
            };
            model.addRow(row);

            totalDue += rs.getDouble("amount_due");
        }

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error loading history: " + e.getMessage());
    }
}

